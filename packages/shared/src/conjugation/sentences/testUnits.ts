export const UNIT_CARDS: Record<'U1' | 'U2' | 'U3' | 'U4', DeckCard[]> = { U1, U2, U3, U4 };

export const UNIT_IDS = ['U1', 'U2', 'U3', 'U4'] as const;
export type UnitId = (typeof UNIT_IDS)[number];

/** The deck of a unit as the class uses it: its own cards, the earlier units' cards, present only. */
export function unitDeck(unit: UnitId, entries: string[], overrides: Partial<SentenceDeck> = {}): SentenceDeck {
  const index = UNIT_IDS.indexOf(unit);
  return {
    tenses: ['present'],
    vosotros: false,
    vos: null,
    entries,
    cards: UNIT_CARDS[unit],
    earlierCards: UNIT_IDS.slice(0, index).flatMap((u) => UNIT_CARDS[u]),
    ...overrides,
  };
}
