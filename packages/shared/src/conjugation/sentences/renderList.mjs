// Writes the reviewers' list: every built-in sentence per unit and entry, filled in (form in bold), with the English.
// Build shared first, then: node src/conjugation/sentences/renderList.mjs rendered.md
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const D = fileURLToPath(new URL('../../../dist/conjugation', import.meta.url));
const { detectVerbs, cellsFor } = await import(D+'/index.js');
const S = await import(D+'/sentences/index.js');
const { UNIT_CARDS, UNIT_IDS, unitDeck } = await import(D+'/sentences/testUnits.js');
const out = [];
const P = { yo:'yo', tu:'tú', el:'él/ella/usted', nosotros:'nosotros', ellos:'ellos/ellas/ustedes' };
let grand = 0; const summary = [];
const body = [];
for (const u of UNIT_IDS) {
  const entries = detectVerbs(UNIT_CARDS[u]).map(v=>v.infinitive);
  const deck = unitDeck(u, entries);
  body.push(`\n## ${u}\n`);
  let unitCount = 0; const missing = [];
  for (const e of entries) {
    const cells = cellsFor(e, deck.tenses, {vosotros:false});
    let count = 0;
    const byFrame = new Map();
    for (const c of cells) {
      const pool = S.sentencePool(e, c, deck);
      if (!pool.length) missing.push(`${e} ${P[c.person]}${c.number ? ' ' + c.number : ''}`);
      for (const r of pool) {
        const list = byFrame.get(r.frameId) ?? []; list.push({ r, c }); byFrame.set(r.frameId, list);
      }
      count += pool.length;
    }
    unitCount += count;
    body.push(`\n### ${e} (${count} sentences, ${byFrame.size} frames)\n`);
    for (const [fid, list] of byFrame) {
      body.push(`\n**${fid}**\n`);
      for (const { r, c } of list) {
        const filled = `${r.before} **${r.answers[0]}** ${r.after}`.replace(/\s+/g,' ').trim();
        const cap = filled.startsWith('**') ? filled.replace(/^\*\*(.)/, (m, ch) => '**' + ch.toUpperCase()) : filled;
        body.push(`- ${cap} — ${r.english ?? '(no English)'} · _${P[c.person]}${c.number ? ' ' + c.number : ''}_`);
      }
    }
  }
  grand += unitCount;
  summary.push(`| ${u} | ${entries.length} | ${unitCount} | ${missing.length ? missing.join(', ') : 'none'} |`);
}
out.push('# Built-in sentences, rendered');
out.push('');
out.push(`Generated by packages/shared/src/conjugation/sentences/renderList.mjs. Every sentence below passed validate() for its unit's settings (present only, vosotros off, no vos; vocabulary = the unit's cards + earlier units + the core list). The verb form in bold is the engine's; the English shows after the answer. Grouped by entry, then frame; the italic tag is the cell.`);
out.push('');
out.push('| Unit | Entries | Sentences | Cells without a sentence |');
out.push('|---|---|---|---|');
out.push(...summary);
out.push(`\nTotal: ${grand} sentences.`);
out.push(...body);
if (!process.argv[2]) throw new Error('usage: node renderList.mjs <out.md>');
fs.writeFileSync(process.argv[2], out.join('\n') + '\n');
console.log(summary.join('\n'), grand);
